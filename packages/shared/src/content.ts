function base(c: Common) {
  return {
    id: c.id,
    area: c.area,
    topic: TOPICS[c.id] ?? c.area,
    intro: INTROS[c.id] ?? '',
    side: c.side,
    stem: c.stem,
    fragments: frags(c.id, c.f),
    explanation: c.why,
    difficulty: c.d,
    deepen: c.deepen ?? [],
    bridge: c.bridge ?? [],
  };
}

function choice(c: Common & { options: string[]; answer: number }): Question {
  return { ...base(c), type: 'choice', options: c.options, answer: c.answer };
}
function estimate(c: Common & { answer: number; tol: number; unit: string }): Question {
  return { ...base(c), type: 'estimate', answer: c.answer, tolerance: c.tol, unit: c.unit };
}
function order(c: Common & { items: string[] }): Question {
  return { ...base(c), type: 'order', items: c.items };
}
function truefalse(c: Common & { answer: boolean }): Question {
  return { ...base(c), type: 'truefalse', answer: c.answer };
}
function match(c: Common & { pairs: [string, string][] }): Question {
  return { ...base(c), type: 'match', pairs: c.pairs };
}
function cloze(c: Common & { text: string; answers: string[]; bank: string[] }): Question {
  return { ...base(c), type: 'cloze', text: c.text, answers: c.answers, bank: c.bank };
}

